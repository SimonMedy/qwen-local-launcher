$infos = New-Object System.Collections.Generic.List[object]

function Add-Info {
    param($Info)
    [void]$infos.Add($Info)
    $status = if ($Info.GpuReady) { 'GPU ready' } elseif ($Info.Works) { 'No GPU' } else { 'Error' }
    $item = New-Object System.Windows.Forms.ListViewItem($status)
    [void]$item.SubItems.Add($Info.Backend)
    [void]$item.SubItems.Add($Info.Path)
    $item.Tag = $infos.Count - 1
    [void]$list.Items.Add($item)
}

foreach ($candidate in (Get-Candidates)) {
    Add-Info (Test-Candidate -Path $candidate)
}

$list.add_SelectedIndexChanged({
    if ($list.SelectedItems.Count -eq 0) {
        $save.Enabled = $false
        $details.Text = ''
        return
    }
    $info = $infos[[int]$list.SelectedItems[0].Tag]
    $save.Enabled = $info.Works
    $details.Text = "Backend: $($info.Backend)`r`nPath: $($info.Path)`r`n`r`n$($info.Version)`r`n`r`n$($info.Devices)"
})

$browse.add_Click({
    $dialog = New-Object System.Windows.Forms.OpenFileDialog
    $dialog.Title = 'Select llama-server.exe'
    $dialog.Filter = 'llama-server.exe|llama-server.exe|Executables (*.exe)|*.exe'
    if ($dialog.ShowDialog($form) -eq [System.Windows.Forms.DialogResult]::OK) {
        $path = $dialog.FileName
        $found = $false
        foreach ($info in $infos) {
            if ($info.Path -ieq $path) { $found = $true; break }
        }
        if (-not $found) { Add-Info (Test-Candidate -Path $path) }
        foreach ($item in $list.Items) {
            if ($item.SubItems[2].Text -ieq $path) {
                $item.Selected = $true
                break
            }
        }
    }
    $dialog.Dispose()
})

$save.add_Click({
    if ($list.SelectedItems.Count -eq 0) { return }
    $info = $infos[[int]$list.SelectedItems[0].Tag]
    if (-not $info.Works) { return }
    Save-PathConfig -Path $info.Path
    $form.DialogResult = [System.Windows.Forms.DialogResult]::OK
    $form.Close()
})

$preferred = $null
foreach ($item in $list.Items) {
    $info = $infos[[int]$item.Tag]
    if ($info.GpuReady) { $preferred = $item; break }
}
if (-not $preferred -and $list.Items.Count -gt 0) { $preferred = $list.Items[0] }
if ($preferred) { $preferred.Selected = $true }

$result = $form.ShowDialog()
