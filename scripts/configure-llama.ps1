$root = Split-Path -Parent $PSScriptRoot
$configDir = Join-Path $root 'config'
$localConfigPath = Join-Path $configDir 'local.psd1'

function Get-ConfiguredPath {
    if (-not (Test-Path -LiteralPath $localConfigPath)) { return $null }
    try {
        $local = Import-PowerShellDataFile -LiteralPath $localConfigPath
        if (-not $local.LlamaServerPath) { return $null }
        $path = [Environment]::ExpandEnvironmentVariables([string]$local.LlamaServerPath)
        if (Test-Path -LiteralPath $path -PathType Leaf) {
            return (Resolve-Path -LiteralPath $path).Path
        }
    } catch {}
    return $null
}

function Get-Candidates {
    $seen = @{}
    $result = New-Object System.Collections.Generic.List[string]

    function Add-Candidate {
        param([string]$Path)
        if ([string]::IsNullOrWhiteSpace($Path)) { return }
        try {
            $expanded = [Environment]::ExpandEnvironmentVariables($Path)
            if (-not (Test-Path -LiteralPath $expanded -PathType Leaf)) { return }
            $resolved = (Resolve-Path -LiteralPath $expanded).Path
            $key = $resolved.ToLowerInvariant()
            if (-not $seen.ContainsKey($key)) {
                $seen[$key] = $true
                [void]$result.Add($resolved)
            }
        } catch {}
    }

    Add-Candidate (Get-ConfiguredPath)
    Add-Candidate $env:QWEN_LLAMA_SERVER
    Add-Candidate (Join-Path $root 'llama.cpp\llama-server.exe')

    $command = Get-Command 'llama-server.exe' -ErrorAction SilentlyContinue
    if ($command) { Add-Candidate $command.Source }

    $searchRoots = @('C:\AI\llama.cpp')
    if ($env:LOCALAPPDATA) { $searchRoots += (Join-Path $env:LOCALAPPDATA 'llama.cpp') }
    if ($env:USERPROFILE) { $searchRoots += (Join-Path $env:USERPROFILE 'llama.cpp') }

    foreach ($searchRoot in $searchRoots) {
        if (-not (Test-Path -LiteralPath $searchRoot -PathType Container)) { continue }
        Get-ChildItem -LiteralPath $searchRoot -Filter 'llama-server.exe' -File -Recurse -ErrorAction SilentlyContinue |
            ForEach-Object { Add-Candidate $_.FullName }
    }

    return @($result)
}

function Test-Candidate {
    param([Parameter(Mandatory)][string]$Path)

    $backend = 'Unknown'
    if ($Path -match '(?i)vulkan') { $backend = 'Vulkan' }
    elseif ($Path -match '(?i)rocm|hip') { $backend = 'ROCm/HIP' }

    $version = ''
    $devices = ''
    $works = $false
    $gpuReady = $false

    try {
        $version = (& $Path --version 2>&1 | Out-String).Trim()
        $devices = (& $Path --list-devices 2>&1 | Out-String).Trim()
        $works = $true
        if ($devices -match '(?im)^\s+\S*\d+:' -and $devices -notmatch '(?im)^\s*\(none\)\s*$') {
            $gpuReady = $true
        }
    } catch {
        $devices = $_.Exception.Message
    }

    return [pscustomobject]@{
        Path = $Path
        Backend = $backend
        Version = $version
        Devices = $devices
        Works = $works
        GpuReady = $gpuReady
    }
}

function Save-PathConfig {
    param([Parameter(Mandatory)][string]$Path)

    New-Item -ItemType Directory -Force -Path $configDir | Out-Null
    $escaped = $Path.Replace("'", "''")
    $content = "@{`r`n    # Generated by Qwen Local Launcher. This file is ignored by Git.`r`n    LlamaServerPath = '$escaped'`r`n}`r`n"
    $encoding = New-Object Text.UTF8Encoding($false)
    [IO.File]::WriteAllText($localConfigPath, $content, $encoding)
}

